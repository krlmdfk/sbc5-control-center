#!/usr/bin/env python3
from pathlib import Path
import re

path = Path("local_apps/sbc5_control_center/Dockerfile")
text = path.read_text(encoding="utf-8")

runtime_paths: set[str] = set()
for line in text.splitlines():
    stripped = line.strip()
    if not stripped.startswith("COPY "):
        continue
    parts = stripped.split()
    from_stage = len(parts) >= 2 and parts[1].startswith("--from=")
    source_index = 2 if from_stage else 1
    if len(parts) <= source_index + 1:
        continue
    sources = parts[source_index:-1]
    dest = parts[-1]
    if not dest.startswith("/"):
        continue
    if dest.endswith("/"):
        for source in sources:
            runtime_paths.add(dest.rstrip("/") + "/" + Path(source).name)
    else:
        runtime_paths.add(dest)

# Paths generated by RUN commands before the chmod step.
runtime_paths.add("/usr/local/bin/sbc5-core")

chmod_block_match = re.search(r"RUN chmod a\+x (?P<body>.*?)(?:\n\n|\nENTRYPOINT)", text, re.S)
if not chmod_block_match:
    raise SystemExit("Dockerfile chmod runtime block not found")

body = chmod_block_match.group("body").replace("\\\n", " ")
chmod_paths = [token for token in body.split() if token.startswith("/")]
missing = [item for item in chmod_paths if item not in runtime_paths]

if missing:
    raise SystemExit("Dockerfile chmod references missing runtime paths: " + ", ".join(missing))

required = {"/ai_cooling.py", "/ai_cooling_v5_2.py", "/thermal_active_policy.py"}
not_packaged = sorted(required - runtime_paths)
if not_packaged:
    raise SystemExit("AI Cooling v5.2 runtime paths are not packaged: " + ", ".join(not_packaged))

print("Dockerfile runtime path validation PASS")
